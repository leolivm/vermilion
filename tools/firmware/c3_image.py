#!/usr/bin/env python3
"""c3_image.py [--fw FILE] [--out FILE]: generate src/phxbringup/phx_c3_image.inc from the user's own copy of
linux-firmware amdgpu/dcn_3_2_0_dmcub.bin (default: $HOME/gpu/fw/navi31/dcn_3_2_0_dmcub.bin, see fetch_firmware.sh).

PhxBringup's cold-boot PHY fix (debug.phxc3, PhxC3Load.h) streams a 0xA000-byte slice of that file to the PHY SRAM.
The slice is AMD microcode under LICENSE.amdgpu (binary redistribution only), so this repository ships the generator,
not the generated header: the build creates it locally (scripts/build/kext.sh). The slice is checked against a sha256
before anything is written; any other firmware revision is refused.
"""
import hashlib, os, struct, sys, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
FW = os.path.join(os.path.expanduser('~'), 'gpu', 'fw', 'navi31', 'dcn_3_2_0_dmcub.bin')
INC = os.path.join(ROOT, 'src', 'phxbringup', 'phx_c3_image.inc')
OFF, LEN, SHA = 0xE200, 0xA000, 'd51426610de22c60'


def arg(name, default):
    a = sys.argv
    return a[a.index(name) + 1] if name in a else default


def main():
    fw, out = arg('--fw', FW), arg('--out', INC)
    b = open(fw, 'rb').read()
    s = b[OFF:OFF + LEN]
    if len(s) != LEN:
        sys.exit('%s: shorter than 0x%x' % (fw, OFF + LEN))
    sha = hashlib.sha256(s).hexdigest()
    if sha[:16] != SHA:
        sys.exit('%s: slice sha256 %s, expected prefix %s (unsupported firmware revision)' % (fw, sha, SHA))
    h = struct.unpack('<%dH' % (LEN // 2), s)
    o = ['// phx_c3_image.inc: GENERATED by tools/firmware/c3_image.py from linux-firmware amdgpu/dcn_3_2_0_dmcub.bin',
         '// (file md5 %s), file offset 0x%X, 0x%X bytes as %d little-endian halfwords; slice sha256 %s.' % (hashlib.md5(b).hexdigest(), OFF, LEN, LEN // 2, sha),
         '// AMD microcode, Copyright (C) Advanced Micro Devices, Inc., LICENSE.amdgpu. Local build input: do not commit.',
         'static constexpr unsigned kPhxC3ImageWords = %du;' % (LEN // 2),
         'static constexpr uint32_t kPhxC3ImageCrc32 = 0x%08xu;' % (zlib.crc32(s) & 0xffffffff),
         'static const uint16_t kPhxC3Image[%d] = {' % (LEN // 2)]
    for i in range(0, len(h), 16):
        o.append('    ' + ', '.join('0x%04x' % x for x in h[i:i + 16]) + ',')
    o.append('};')
    open(out, 'w').write('\n'.join(o) + '\n')
    print('wrote %s' % out)


if __name__ == '__main__':
    main()
